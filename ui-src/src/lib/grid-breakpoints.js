// n-grid 的断点表（只在这里定义一次）。
//
// 为什么键要写成数字：
// naive-ui 的 NGrid 在 `responsive="screen"` 下把 cols 的序号前缀当成
// **断点名**（vooks 的 useBreakpoints 返回的是匹配到的名字数组），
// 所以 `cols="1 700:2"` 里的 `700:` 只有在断点表里存在一个叫 "700" 的键时才
// 匹配得到；用 naive-ui 默认的 xs/s/m/l 名字，`700:` 会一路落到默认值 1，
// 整页栅格永远是单列。把键写成数字，组件里的 cols 就能直接读成像素阈值，
// 阈值本身也只在这里出现一次。
//
// 取值不是猜的：
//   700 —— 旧手写 CSS 的 760px 断点（两栏 / 三下拉 / 两格展开区）；
//   640 —— 打分服务卡片的「模型:超时 = 2:1」那一格（`cols="1 640:3"`）；
//   520 —— 通道四格在窄屏先收成两列的那一档；
//   0   —— 兜底，任何宽度都匹配（等于 naive-ui 的 xs）。
//
// 只影响走 breakpoints 的组件（本仓库只有 n-grid）。任何组件都不要另写一份
// 断点表，否则两套阈值一定会对不上。

export const BREAKPOINTS = Object.freeze({
  0: 0,
  520: 520,
  640: 640,
  700: 700,
});
